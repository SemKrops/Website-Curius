// Een icoon bij elk onderdeel van het menu, op basis van het adres of de naam.
export function icoonVoor(tekst) {
  const s = String(tekst ?? '').toLowerCase();
  const regels = [
    [/vereniging|association/, 'landmark'],
    [/activiteit|event|kalender|calendar/, 'calendar'],
    [/carri|career|vacature|vacanc|partner/, 'briefcase'],
    [/onderwijs|education|bachelor|master|studie|study/, 'graduation'],
    [/media|foto|photo|consul|expo/, 'camera'],
    [/cafe|café/, 'coffee'],
    [/welzijn|well-being|vertrouwen|trust/, 'heart'],
    [/contact/, 'mail'],
    [/eerstejaars|first-year|woej/, 'sparkles'],
    [/nieuws|news/, 'megaphone'],
    [/lid-worden|become|lid worden|member/, 'userPlus'],
    [/boek|book/, 'book'],
    [/festival|frontrunner/, 'ticket'],
    [/bestuur|board|commissie|committee|ereleden|honour|vrienden|friends/, 'users'],
  ];
  return regels.find(([re]) => re.test(s))?.[1] ?? 'file';
}
